const PLACES = [
  [/парк/, 'в парке'],
  [/пруд/, 'у пруда'],
  [/офис/, 'в офисе'],
  [/кафе|кофейн/, 'в кафе'],
  [/мор[еяю]/, 'у моря'],
  [/лес/, 'в лесу'],
  [/дожд/, 'под дождём'],
  [/снег/, 'в снегу'],
  [/метро/, 'в метро'],
  [/кино/, 'в кино'],
  [/концерт/, 'на концерте'],
  [/прогулк|гуляли|гулял/, 'на прогулке'],
  [/поезд|дорог|путешеств/, 'в дороге'],
  [/горы|горах/, 'в горах'],
  [/озер/, 'у озера'],
  [/река|реки|речк/, 'у реки'],
  [/дома|домой|квартир/, 'дома'],
  [/универ|лекци|учёб|учеб|экзамен/, 'за учёбой'],
  [/работ|проект|дедлайн|сдач/, 'за работой'],
  [/друз|подруг|друж/, 'с друзьями'],
  [/семь|родител|мам[аеуы]|пап[аеуы]/, 'с семьёй'],
  [/какао/, 'с какао'],
  [/кофе/, 'с кофе'],
  [/музык|наушник/, 'под музыку'],
  [/звёзд|звезд/, 'под звёздами'],
  [/закат/, 'на закате'],
  [/ветер|ветр/, 'на ветру'],
  [/пляж|песок|песк/, 'на пляже'],
  [/костёр|костер/, 'у костра'],
  [/книг|читал/, 'за книгой'],
];
const TIMES = [
  [/утр|рассвет/, 'Утро'],
  [/вечер|закат/, 'Вечер'],
  [/ноч[ьи]|полноч/, 'Ночь'],
  [/днём|днем|полдень|обед/, 'День'],
];
const MOODN = { calm: 'тихий', tense: 'собранный', bright: 'яркий', melancholy: 'задумчивый' };

export function makeTitle(text, mood, hour = 12) {
  const t = text.toLowerCase();
  let time = null;
  for (const [re, w] of TIMES)
    if (re.test(t)) {
      time = w;
      break;
    }
  if (!time) time = hour < 5 ? 'Ночь' : hour < 11 ? 'Утро' : hour < 17 ? 'День' : hour < 22 ? 'Вечер' : 'Ночь';
  const found = [];
  for (const [re, w] of PLACES) if (re.test(t) && !found.includes(w)) found.push(w);
  const parts = found.slice(0, 2);
  if (!parts.length) {
    const adj = MOODN[mood] || 'особенный';
    return cap(`${adj} ${time.toLowerCase()}`);
  }
  return `${time} ${parts.join(' ')}`;
}
const cap = s => s[0].toUpperCase() + s.slice(1);
